def init_knowledge_base():
    """初始化知识库表并填充数据"""
    print(f"[INFO] 正在连接数据库: {DB_PATH}")
    
    # 确保 data 目录存在
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    
    conn = sqlite3.connect(str(DB_PATH))
    cursor = conn.cursor()
    
    # 1. 创建知识库表
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS knowledge_base (
            id            INTEGER PRIMARY KEY AUTOINCREMENT,
            defect_type   VARCHAR(50) NOT NULL,
            standard_code VARCHAR(100) NOT NULL,
            title         TEXT NOT NULL,
            content       TEXT NOT NULL,
            embeddings    TEXT DEFAULT ''
        )
    """)
    
    # 创建索引
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_kb_defect_type ON knowledge_base(defect_type)")
    conn.commit()
    
    # 2. 清理历史数据（避免重复插入）
    cursor.execute("DELETE FROM knowledge_base")
    conn.commit()
    
    # 3. 批量插入
    inserted = 0
    for item in STANDARDS_DATA:
        cursor.execute(
            "INSERT INTO knowledge_base (defect_type, standard_code, title, content) VALUES (?, ?, ?, ?)",
            (item["defect_type"], item["standard_code"], item["title"], item["content"])
        )
        inserted += 1
        
    conn.commit()
    print(f"[SUCCESS] 知识库初始化成功！共导入 {inserted} 条核心国家钢铁标准与工业成因切片。")
    
    # 验证查询
    cursor.execute("SELECT COUNT(*) FROM knowledge_base")
    count = cursor.fetchone()[0]
    print(f"[INFO] 验证：当前知识库表中共有 {count} 条记录。")
    
    conn.close()

if __name__ == "__main__":
    init_knowledge_base()
